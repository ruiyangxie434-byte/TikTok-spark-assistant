from pathlib import Path
import llvmlite.ir as ir
import llvmlite.binding as llvm
llvm.initialize_all_targets(); llvm.initialize_all_asmprinters()
m=ir.Module(name='spark_node_jni');m.triple='aarch64-linux-android'
i8,i32,i64=ir.IntType(8),ir.IntType(32),ir.IntType(64)
p=i8.as_pointer(); env=p.as_pointer(); null=ir.Constant(p,None)
get_type=ir.FunctionType(p,[env,p,p]); release_type=ir.FunctionType(ir.VoidType(),[env,p,p])
start=ir.Function(m,ir.FunctionType(i32,[env,p,p]),name='Java_app_local_spark_background_NodeEngine_start')
b=ir.IRBuilder(start.append_basic_block('entry'))
table=b.bitcast(b.load(start.args[0]),p.as_pointer())
get=b.bitcast(b.load(b.gep(table,[ir.Constant(i64,169)])),get_type.as_pointer())
release=b.bitcast(b.load(b.gep(table,[ir.Constant(i64,170)])),release_type.as_pointer())
chars=b.call(get,[start.args[0],start.args[2],null])
missing=start.append_basic_block('missing_string'); ready=start.append_basic_block('ready')
b.cbranch(b.icmp_unsigned('==',chars,null),missing,ready)
b.position_at_end(missing);b.ret(ir.Constant(i32,-2));b.position_at_end(ready)
strlen=ir.Function(m,ir.FunctionType(i64,[p]),name='strlen')
malloc=ir.Function(m,ir.FunctionType(p,[i64]),name='malloc')
free=ir.Function(m,ir.FunctionType(ir.VoidType(),[p]),name='free')
copy=ir.Function(m,ir.FunctionType(p,[p,p,i64]),name='memcpy')
length=b.add(b.call(strlen,[chars]),ir.Constant(i64,1))
buffer=b.call(malloc,[b.add(length,ir.Constant(i64,5))])
failed=start.append_basic_block('allocation_failed'); allocated=start.append_basic_block('allocated')
b.cbranch(b.icmp_unsigned('==',buffer,null),failed,allocated)
b.position_at_end(failed);b.call(release,[start.args[0],start.args[2],chars]);b.ret(ir.Constant(i32,-3))
b.position_at_end(allocated)
name=ir.GlobalVariable(m,ir.ArrayType(i8,5),name='node_name');name.linkage='private';name.global_constant=True;name.initializer=ir.Constant(name.type.pointee,bytearray(b'node\0'))
nameptr=b.gep(name,[ir.Constant(i32,0),ir.Constant(i32,0)])
b.call(copy,[buffer,nameptr,ir.Constant(i64,5)])
script=b.gep(buffer,[ir.Constant(i64,5)]);b.call(copy,[script,chars,length])
argv=b.alloca(p,ir.Constant(i32,3))
for index,value in enumerate([buffer,script,null]):b.store(value,b.gep(argv,[ir.Constant(i64,index)]))
node=ir.Function(m,ir.FunctionType(i32,[i32,p.as_pointer()]),name='_ZN4node5StartEiPPc')
result=b.call(node,[ir.Constant(i32,2),argv])
b.call(free,[buffer]);b.call(release,[start.args[0],start.args[2],chars]);b.ret(result)
root=Path('work/node-mobile');(root/'bridge.ll').write_text(str(m),encoding='utf-8')
module=llvm.parse_assembly(str(m));module.verify()
target=llvm.Target.from_triple(m.triple).create_target_machine(reloc='pic')
(root/'bridge.o').write_bytes(target.emit_object(module))
print('ARM64 JNI bridge object compiled:',(root/'bridge.o').stat().st_size,'bytes')
